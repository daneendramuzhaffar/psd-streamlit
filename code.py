import pandas as pd
import plotly.express as px
import json

# 1. Load Data Ulang (Agar variabel bersih)
csv_filename = '/content/jumlah_kasus_hiv_berdasarkan_kelompok_umur_v1_data.csv'
geojso_filename = '/content/jawa_barat_32_batas_kabkota.geojson'

df = pd.read_csv(csv_filename)
with open(geojson_filename, 'r') as f:
    jabar_geojson = json.load(f)

# ------------------------------------------------------------------------------
# VISUALISASI 1: TREN TOTAL KASUS JAWA BARAT (Line Chart)
# ------------------------------------------------------------------------------
# Agregasi data per tahun
df_trend_jabar = df.groupby('tahun')['jumlah_kasus'].sum().reset_index()

fig_line = px.line(
    df_trend_jabar,
    x='tahun',
    y='jumlah_kasus',
    markers=True,
    title='<b>Tren Total Kasus HIV/AIDS Jawa Barat (Perkembangan Tahunan)</b>',
    labels={'jumlah_kasus': 'Total Kasus', 'tahun': 'Tahun'}
)
fig_line.update_traces(line_color='red', line_width=4)
fig_line.show()


# ------------------------------------------------------------------------------
# VISUALISASI 2: PERBANDINGAN TREN 5 KOTA DENGAN KASUS TERTINGGI
# ------------------------------------------------------------------------------
# Mencari 5 kota dengan total kasus terbanyak sepanjang sejarah
top_5_cities = df.groupby('nama_kabupaten_kota')['jumlah_kasus'].sum().nlargest(5).index.tolist()

# Filter data hanya untuk 5 kota tersebut
df_top_5 = df[df['nama_kabupaten_kota'].isin(top_5_cities)]
df_trend_kota = df_top_5.groupby(['nama_kabupaten_kota', 'tahun'])['jumlah_kasus'].sum().reset_index()

fig_multiline = px.line(
    df_trend_kota,
    x='tahun',
    y='jumlah_kasus',
    color='nama_kabupaten_kota',
    markers=True,
    title='<b>Dinamika Kasus di 5 Wilayah "Hotspot" Utama</b>',
    labels={'nama_kabupaten_kota': 'Wilayah'}
)
fig_multiline.show()


# ------------------------------------------------------------------------------
# VISUALISASI 3: PETA ANIMASI (TIMELINE MAP)
# ------------------------------------------------------------------------------
# Persiapan Data untuk Peta Animasi
df_map_yearly = df.groupby(['nama_kabupaten_kota', 'tahun'])['jumlah_kasus'].sum().reset_index()

